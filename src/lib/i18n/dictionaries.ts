const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";

/** Arabic-Indic digits for Arabic text. */
export function num(v: string | number): string {
  return String(v).replace(/[0-9]/g, (d) => AR_DIGITS[Number(d)]);
}

export const dictionaries: Record<Lang, Record<MessageKey, Entry>> = { en, ar };

export function translate(lang: Lang, key: MessageKey, params: Params = {}): string {
  const entry = dictionaries[lang][key] ?? dictionaries.en[key];
  return typeof entry === "function" ? entry(params) : entry;
}

export function formatNumber(lang: Lang, n: number | string): string {
  return lang === "ar" ? num(n) : String(n);
}
